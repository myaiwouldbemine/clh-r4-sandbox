#!/usr/bin/env python3
r"""
Issue #11 Archive Record Builder (Safe Template-Based)

Safely generate Archive Closure Record with proper handling of:
- Special characters: & | / \ 
- Newlines and formatting
- Dynamic content substitution

Uses Python string template to avoid sed escaping complexity.
"""

from typing import Dict, Optional
from string import Template


class ArchiveRecordBuilder:
    """Build Archive Closure Record with template-safe substitution."""
    
    # Template with $-style placeholders (Template-safe)
    TEMPLATE = """## 📦 Archive Closure Record

**Upload Consolidated**
- PR: [#$pr_number]($pr_url) — $pr_title
- Merge Commit: [$merge_sha_short](https://github.com/$repo/commit/$merge_sha)
- Method: $merge_method

**Verification**
- CI: governance-tests ✅, docs-check ✅
- PR ↔ Issue: Linked ✅
- Merge: Complete ✅
- Readback: [$run_url_display]($run_url)

**Archive Status**
Issue #$issue_number — Archive consolidated.
(Closing issue indicates upload/archive completion, not learning conclusion.)

---
*Record generated by Issue #11 archive automation.*
"""
    
    @staticmethod
    def build(
        pr_number: int,
        pr_url: str,
        pr_title: str,
        merge_sha: str,
        repo: str,
        merge_method: str,
        issue_number: int,
        run_url: Optional[str] = None,
    ) -> str:
        """
        Build archive record with safe template substitution.
        
        Args:
            pr_number: PR number (e.g., 12)
            pr_url: Full PR URL
            pr_title: PR title (may contain special characters)
            merge_sha: Full 40-char merge commit SHA
            repo: Repository in "owner/repo" format
            merge_method: Merge method (e.g., "squash")
            issue_number: Issue number (e.g., 11)
            run_url: Optional workflow run URL
        
        Returns:
            Rendered archive record as string
        
        Raises:
            ValueError: If SHA is not 40 characters
        """
        if len(merge_sha) != 40:
            raise ValueError(f"Merge SHA must be 40 chars, got {len(merge_sha)}: {merge_sha}")
        
        merge_sha_short = merge_sha[:8]
        run_url_display = run_url if run_url else "Not available"
        run_url_safe = run_url if run_url else ""
        
        # Build substitution dict
        # Python's Template uses $variable syntax (safe from shell issues)
        template_vars = {
            'pr_number': str(pr_number),
            'pr_url': pr_url,
            'pr_title': pr_title,  # No escaping needed - Template handles it
            'merge_sha_short': merge_sha_short,
            'merge_sha': merge_sha,
            'repo': repo,
            'merge_method': merge_method,
            'issue_number': str(issue_number),
            'run_url': run_url_safe,
            'run_url_display': run_url_display,
        }
        
        # Substitute using Template (safe - no shell interpretation)
        template = Template(ArchiveRecordBuilder.TEMPLATE)
        return template.substitute(template_vars)
    
    @staticmethod
    def validate_special_chars(text: str) -> bool:
        """
        Verify text can be safely used in archive record.
        
        Args:
            text: Text to validate
        
        Returns:
            True if text is safe
        """
        # Any UTF-8 text is safe for Python Template
        # Only validation needed is basic sanity check
        if not isinstance(text, str):
            return False
        return True
